package com.chu7.vuecomponentassistant.exceptions;

public class VueKitException extends Exception {
	public VueKitException() { super(); }
	public VueKitException(String message) { super(message); }
	public VueKitException(String message, Throwable cause) { super(message, cause); }
	public VueKitException(Throwable cause) { super(cause); }
} 